"""Benchmark: signature rules vs Isolation Forest vs hybrid. Writes docs/RESULTS.md (+ chart)."""
import numpy as np

from .features import vectorize
from .model import Detector
from .rules import decide, rule_flags
from .simulator import ATTACKS, BENIGN_W_TEST, BENIGN_W_TRAIN, dataset


def metrics(y_true, y_pred):
    y, p = np.array(y_true), np.array(y_pred)
    tp, fp = int((y & p).sum()), int((~y & p).sum())
    fn, tn = int((y & ~p).sum()), int((~y & ~p).sum())
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    return dict(precision=prec, recall=rec, fpr=fp / (fp + tn) if fp + tn else 0.0,
                f1=2 * prec * rec / (prec + rec) if prec + rec else 0.0)


def run(seed=7, n_train=3000, n_test=1500, n_attack=150, fpr_target=0.02):
    tr_ev, _ = dataset(n_train, 0, BENIGN_W_TRAIN, seed)
    det = Detector(fpr_target=fpr_target).fit([vectorize(e) for e in tr_ev])
    te_ev, labels = dataset(n_test, n_attack, BENIGN_W_TEST, seed + 1)
    X = [vectorize(e) for e in te_ev]
    y = [l != 0 for l in labels]
    _, ml = det.score_many(X)
    flags = [rule_flags(v) for v in X]
    rules_p = [len(f) >= 1 for f in flags]
    hyb = [decide(f, bool(m), v)[0] for f, m, v in zip(flags, ml, X)]
    res = {"Signature rules": metrics(y, rules_p), "Isolation Forest": metrics(y, list(ml)),
           "Hybrid (KubeSentinel)": metrics(y, hyb)}
    per = {}
    for a in ATTACKS:
        idx = [i for i, l in enumerate(labels) if l == a]
        per[a] = {"Signature rules": np.mean([rules_p[i] for i in idx]),
                  "Isolation Forest": np.mean([ml[i] for i in idx]),
                  "Hybrid (KubeSentinel)": np.mean([hyb[i] for i in idx])}
    return res, per


def report(path="docs/RESULTS.md", chart="docs/results.png"):
    res, per = run()
    L = ["# Evaluation results (SYNTHETIC telemetry)", "",
         "> Generated by `make evaluate`. Synthetic data validates the pipeline; replace with the "
         "real-cluster numbers (docs/EVALUATION.md) before presenting final claims.", "",
         "| Method | Precision | Recall | FPR | F1 |", "|---|---|---|---|---|"]
    for m, r in res.items():
        L.append(f"| {m} | {r['precision']:.3f} | {r['recall']:.3f} | {r['fpr']:.3f} | {r['f1']:.3f} |")
    L += ["", "## Recall per attack scenario", "", "| Attack | Rules | IForest | Hybrid |", "|---|---|---|---|"]
    for a, r in per.items():
        L.append(f"| {a} | {r['Signature rules']:.2f} | {r['Isolation Forest']:.2f} | {r['Hybrid (KubeSentinel)']:.2f} |")
    open(path, "w").write("\n".join(L) + "\n")
    try:
        import matplotlib; matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        names, w = list(per), 0.27
        fig, ax = plt.subplots(figsize=(9, 4))
        for k, m in enumerate(["Signature rules", "Isolation Forest", "Hybrid (KubeSentinel)"]):
            ax.bar(np.arange(len(names)) + k * w, [per[a][m] for a in names], w, label=m)
        ax.set_xticks(np.arange(len(names)) + w); ax.set_xticklabels(names, rotation=20)
        ax.set_ylabel("Recall"); ax.set_title("Detection recall per attack (synthetic)"); ax.legend()
        fig.tight_layout(); fig.savefig(chart, dpi=130)
    except Exception as exc:
        print("chart skipped:", exc)
    print("\n".join(L))
